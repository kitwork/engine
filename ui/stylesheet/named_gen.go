// named_gen writes named.go, the dictionary of named colours, and named_source_test.go, the source
// data the tests hold the dictionary to, from merged.json:
//
//	go run named_gen.go path/to/merged.json
//
// merged.json (decision of 12/10/2026) holds, as "css", the 148 named colours of CSS Color 4 §6.1
// (https://www.w3.org/TR/css-color-4/#named-colors) with their values, grey and gray, aqua and cyan
// among them; as "figmaOnly", the 207 names of Figma's colour list (https://www.figma.com/colors/)
// that CSS does not have, written hyphenated and lowercase (cerulean, burnt-orange, rose-gold); as
// "sameNameOtherHex", the 48 names both lists have with Figma's value and CSS's ([display name, figma,
// css]: CSS wins, the name keeps its CSS value); as "sameHexOtherName", the Figma names that are only
// another name for a CSS colour ([display name, hex, [css names]]): those are no names (navy-blue is
// navy) and a page that writes one is told the CSS name.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"
)

type source struct {
	CSS              map[string]string `json:"css"`
	FigmaOnly        map[string]string `json:"figmaOnly"`
	SameNameOtherHex [][3]string       `json:"sameNameOtherHex"`
	SameHexOtherName []json.RawMessage `json:"sameHexOtherName"`
}

var (
	hexColour = regexp.MustCompile(`^#[0-9a-f]{6}$`)
	cssName   = regexp.MustCompile(`^[a-z]+$`)
	figmaName = regexp.MustCompile(`^[a-z]+(?:-[a-z]+)*$`)
)

// token is a Figma display name as a name: lowercase, words joined by -.
func token(display string) string {
	return strings.Trim(regexp.MustCompile(`[^a-z0-9]+`).ReplaceAllString(strings.ToLower(display), "-"), "-")
}

func main() {
	if len(os.Args) != 2 {
		fail("usage: go run named_gen.go merged.json")
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err.Error())
	}
	var s source
	if err := json.Unmarshal(raw, &s); err != nil {
		fail(err.Error())
	}
	if len(s.CSS) != 148 || len(s.FigmaOnly) != 207 || len(s.SameNameOtherHex) != 48 {
		fail(fmt.Sprintf("merged.json has %d CSS names, %d Figma-only names, %d shared names: want 148, 207, 48", len(s.CSS), len(s.FigmaOnly), len(s.SameNameOtherHex)))
	}
	aliases := map[string]string{} // Figma name → the CSS name of the same colour
	for _, entry := range s.SameHexOtherName {
		var row []json.RawMessage
		var display, hex string
		var names []string
		if json.Unmarshal(entry, &row) != nil || len(row) != 3 || json.Unmarshal(row[0], &display) != nil ||
			json.Unmarshal(row[1], &hex) != nil || json.Unmarshal(row[2], &names) != nil || len(names) != 1 {
			fail(fmt.Sprintf("sameHexOtherName row %s: want [display name, hex, [one CSS name]]", entry))
		}
		name := token(display)
		if s.FigmaOnly[name] != hex || s.CSS[names[0]] != hex {
			fail(fmt.Sprintf("%s (%s) is not %s of CSS (%s)", name, s.FigmaOnly[name], names[0], s.CSS[names[0]]))
		}
		aliases[name] = names[0]
	}
	if len(aliases) != 5 {
		fail(fmt.Sprintf("%d Figma names rename a CSS colour, want 5", len(aliases)))
	}

	named := map[string]string{}
	letters := map[string]string{} // a name's letters → the name: two names must not differ by - alone
	add := func(name, hex string, pattern *regexp.Regexp) {
		if !pattern.MatchString(name) || !hexColour.MatchString(hex) {
			fail(fmt.Sprintf("%q: %q is not a name and a #rrggbb", name, hex))
		}
		key := strings.ReplaceAll(name, "-", "")
		if other, taken := letters[key]; taken {
			fail(fmt.Sprintf("%q and %q are the same letters", other, name))
		}
		letters[key] = name
		named[name] = hex
	}
	for name, hex := range s.CSS {
		add(name, hex, cssName)
	}
	for name, hex := range s.FigmaOnly {
		if aliases[name] != "" {
			continue
		}
		add(name, hex, figmaName)
	}
	if len(named) != 350 {
		fail(fmt.Sprintf("%d names, want 148 + 207 - 5 = 350", len(named)))
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by named_gen.go from merged.json; DO NOT EDIT.

package stylesheet

// namedColours are the colours a .ui page names by their names (decision of 12/10/2026): the 148
// named colours of CSS Color 4, with their CSS values, grey and gray, aqua and cyan among them; and
// the names only Figma's colour list has, hyphenated and lowercase. Where both lists name a colour, it
// has its CSS value. Each is the same colour in light and in dark, like white and black.
var namedColours = map[string]string{
`)
	for _, name := range sortedKeys(named) {
		fmt.Fprintf(&b, "%q: %q,\n", name, named[name])
	}
	b.WriteString(`}

// namedAliases are the Figma names that are only another name for a CSS colour: no names of their own,
// each the CSS name to write instead.
var namedAliases = map[string]string{
`)
	for _, name := range sortedKeys(aliases) {
		fmt.Fprintf(&b, "%q: %q,\n", name, aliases[name])
	}
	b.WriteString("}\n")
	write("named.go", b.Bytes())

	b.Reset()
	b.WriteString(`// Code generated by named_gen.go from merged.json; DO NOT EDIT.

package stylesheet

// The lists the dictionary is made from, as merged.json holds them: CSS Color 4's 148 named colours,
// the 207 names only Figma's colour list has (the five that rename a CSS colour among them), and the
// 48 names both have, with Figma's value and CSS's.

var sourceCSS = map[string]string{
`)
	for _, name := range sortedKeys(s.CSS) {
		fmt.Fprintf(&b, "%q: %q,\n", name, s.CSS[name])
	}
	b.WriteString("}\n\nvar sourceFigmaOnly = map[string]string{\n")
	for _, name := range sortedKeys(s.FigmaOnly) {
		fmt.Fprintf(&b, "%q: %q,\n", name, s.FigmaOnly[name])
	}
	b.WriteString("}\n\n// sourceShared is [display name in Figma, Figma's value, CSS's value].\nvar sourceShared = [][3]string{\n")
	shared := append([][3]string(nil), s.SameNameOtherHex...)
	sort.Slice(shared, func(i, j int) bool { return shared[i][0] < shared[j][0] })
	for _, row := range shared {
		fmt.Fprintf(&b, "{%q, %q, %q},\n", row[0], row[1], row[2])
	}
	b.WriteString("}\n")
	write("named_source_test.go", b.Bytes())
}

func write(file string, source []byte) {
	formatted, err := format.Source(source)
	if err != nil {
		fail(file + ": " + err.Error())
	}
	if err := os.WriteFile(file, formatted, 0o644); err != nil {
		fail(err.Error())
	}
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func fail(message string) {
	fmt.Fprintln(os.Stderr, "named_gen:", message)
	os.Exit(1)
}
