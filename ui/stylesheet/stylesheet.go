// Package stylesheet is the web target of Kitwork UI's presentation. It turns the attributes a .ui
// page writes (padding="4", hover:background="brand+15") into classes named in the page's own words
// and the CSS behind them, and makes the engine's stylesheets of a .ui page. Template pages
// (.kitwork.html) do not use it: they keep jit/css.
//
// A .ui page links these files from /_kitwork/, in this order:
//
//	reboot.<hash>.css  Reboot(): the ground of every page, the same bytes for every site, branch and page
//	colors.<hash>.css  Colors(palette): the colour tokens of one colour chain (router.colors)
//	fonts.<hash>.css   jit/fonts: @font-face and --font-body, --font-code
//	icons.<hash>.css   jit/icons, inside the elements layer (Elements)
//	page.<hash>.css    Rules.File(): the rule of every class any branch of the page can carry
//
// and, only when a class of the page holds while the page is scrolled (scrolled:shadow="small"), one
// script, scrolled.<hash>.js (ScrolledScript), which keeps the flag those rules read.
//
// Precedence comes from four cascade layers, never from selector weight, alphabetical order or which
// <link> Drive leaves first: reboot (browser differences and accessibility floors), elements (how each
// Kitwork element looks before the author writes anything), page (the classes the author's attributes
// became) and show (show="false" medium:show="true": hiding by width beats any display a class sets).
// Every layered file starts with the same statement, LayerStatement, so the order holds however the
// files arrive. Inside a layer every rule weighs the same (zero in reboot.css, one class in a page),
// so the order the generator writes is the whole contract.
//
// A class is the .ui attribute as written — [condition ":"] attribute "-" value: gap-4,
// medium:padding-6, large+hover:background-brand+15, color-ink-30, show-false. Only the CSS
// escapes it.
//
// Every site names, besides its own router.gradients, the gradients built into the engine: the
// standard set (gradients.go), the page backdrops (backdrops.go) and 175 of the 180 gradients of the
// WebGradients collection (webgradients.go, generated by webgradients_gen.go from the collection's
// stylesheet, webgradients.css, github.com/itmeo/webgradients, MIT License, Copyright (c) 2017 itmeo:
// the licence ships next to the data as WEBGRADIENTS_LICENSE). A gradient of the collection keeps its
// name in .ui spelling (Warm Flame is warm-flame) and is the top layer the stylesheet writes, its colours
// at the places of its stops, the same in light and dark; a linear one keeps the stylesheet's direction
// (to right is to-end) or takes its angle's nearest direction word, at most 22.5deg away (20deg in this
// collection: -20deg is to-top). Four are drawn short of the stylesheet: Arielle's Smile and Elegance at
// the one radial size, and the blended layers under Raccoon Back, Elegance and Slick Carbon not drawn.
// Five, a base colour seen through translucent layers, are left out (Coup de Grace, Loon Crest, Sharp
// Glass, Chemic Aqua, Earl Gray); a page writing one is told so. Twelve take another name; a page
// writing the collection's name is told the new one:
//
//	the collection's name  .ui name
//	Young Passion          coral-berry
//	Lady Lips              pink-blush
//	Arielle's Smile        arielles-smile   (an apostrophe is no letter of a name)
//	Itmeo Branding         spring-blue      (the collection's author's own brand)
//	Dirty Beauty           dusty-blue
//	Teen Notebook          periwinkle-pink
//	Sweet Period           indigo-gold
//	Love Kiss              red-peach
//	Passionate Bed         salmon-rose
//	Vicious Stance         deep-slate
//	Light Blue             aqua-sky         (light-blue is the colour lightblue written with a hyphen)
//	Teen Party             magenta-indigo
package stylesheet

import (
	"bytes"
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"strings"
	"sync"
)

// LayerStatement opens every layered stylesheet of a .ui page, in the compact form the files carry.
const LayerStatement = "@layer reboot,elements,page,show;"

// File is one stylesheet the engine serves: its role (reboot, colors, page), its name — the role and
// the first 16 hex characters of the SHA-256 of its bytes, served as /_kitwork/<name>.css — and its
// bytes. The same bytes in one role always have the same name.
type File struct {
	Role, Name string
	CSS        []byte
}

func newFile(role string, css []byte) File {
	sum := sha256.Sum256(css)
	return File{Role: role, Name: role + "." + hex.EncodeToString(sum[:8]), CSS: css}
}

// Elements puts rules another generator makes (jit/icons, jit/logo) into the elements layer, after the
// layer statement: unlayered CSS would beat every layer whatever its weight, so an icon would stay
// visible against a show-false. Empty in, nil out.
func Elements(css []byte) []byte {
	if len(bytes.TrimSpace(css)) == 0 {
		return nil
	}
	out := make([]byte, 0, len(LayerStatement)+len(css)+20)
	out = append(out, LayerStatement...)
	out = append(out, "\n@layer elements{\n"...)
	out = append(out, css...)
	if css[len(css)-1] != '\n' {
		out = append(out, '\n')
	}
	return append(out, "}\n"...)
}

//go:embed reboot.css
var rebootSource string

var reboot = sync.OnceValue(func() File { return newFile("reboot", compact(rebootSource)) })

// Reboot is reboot.<hash>.css: the layer statement, the reboot layer (normalisation and accessibility
// floors) and the elements layer (each Kitwork element's default look and the direction machinery).
// It names tokens through var() and never holds their values, so it is the same for every site,
// branch and page and changes only with the engine. reboot.css is kept readable in the source; the
// file served is it compacted, once, so its name does not depend on how a checkout ends its lines.
func Reboot() File {
	f := reboot()
	f.CSS = bytes.Clone(f.CSS)
	return f
}

// Script is a script the presentation needs, served as /_kitwork/<Name>.js: its role and its name —
// the role and the first 16 hex characters of the SHA-256 of its bytes, like a File — and its bytes.
type Script struct {
	Role, Name string
	JavaScript []byte
}

//go:embed scrolled.js
var scrolledSource string

var scrolledScript = sync.OnceValue(func() Script {
	javascript := compactScript(scrolledSource)
	sum := sha256.Sum256(javascript)
	return Script{Role: "scrolled", Name: "scrolled." + hex.EncodeToString(sum[:8]), JavaScript: javascript}
})

// compactScript drops a script's comment lines, blank lines and indentation, whichever way its lines
// end. It reads only what the engine's own scripts are written as: a comment is a line of its own.
func compactScript(source string) []byte {
	var lines []string
	for _, line := range strings.Split(source, "\n") {
		line = strings.TrimSpace(line)
		if line != "" && !strings.HasPrefix(line, "//") {
			lines = append(lines, line)
		}
	}
	return []byte(strings.Join(lines, "\n") + "\n")
}

// ScrolledScript is scrolled.<hash>.js, what the scrolled: state needs on the web: a few lines that
// keep data-kitwork-scrolled on <html> while the page is scrolled away from its top (a few pixels, so
// a wobble at the top does not flicker it), which every scrolled: rule reads. The same bytes for every
// site and page; the engine links it, deferred, only to a page whose HTML can carry a scrolled: class
// (Rules.Scrolled), with or without the kernel. Served compacted — no comment line, no indentation —
// so its name does not depend on how a checkout ends its lines.
func ScrolledScript() Script {
	s := scrolledScript()
	s.JavaScript = bytes.Clone(s.JavaScript)
	return s
}

// ElementWords are the classes the engine writes without any attribute and reboot.css styles: the
// direction of a container, the parent of a placed child, the .ui tag word where several tags share
// one HTML element, and the parts of the hosts it writes for Kitwork's own components (the
// progressbar, the reader, the toast). No page rule exists for them.
func ElementWords() []string {
	return []string{
		"badge", "breadcrumb", "card", "error", "field", "flex-column", "flex-row", "grid", "hint",
		"place-anchor", "popover", "progressbar", "reader", "toast",
	}
}

// ElementWeights are the font weights Kitwork's elements have before the author writes a weight:
// text 400 (the browser's normal, which reboot.css leaves alone), a badge 500 and a heading 600 (both
// set in reboot.css). With Rules.Weights, the weights the page writes, they are the weights
// fonts.<hash>.css ships for the elements a page has.
func ElementWeights() map[string]int {
	return map[string]int{"text": 400, "badge": 500, "heading": 600}
}

// compact writes CSS without comments and without the whitespace CSS does not read. It keeps a space
// where CSS reads one — a descendant combinator before a pseudo-class (":where(a) :where(b)"), "and
// (" in a media query, between the parts of a value — and copies strings as they are.
func compact(source string) []byte {
	out := make([]byte, 0, len(source)/2)
	space := false
	for i := 0; i < len(source); {
		c := source[i]
		switch {
		case c == '/' && i+1 < len(source) && source[i+1] == '*':
			end := indexFrom(source, "*/", i+2)
			if end < 0 {
				i = len(source)
			} else {
				i = end + 2
			}
			space = true
			continue
		case c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f':
			space = true
			i++
			continue
		}
		if space && len(out) > 0 && !dropsSpaceBefore(c) && !dropsSpaceAfter(out[len(out)-1]) {
			out = append(out, ' ')
		}
		space = false
		if c == '"' || c == '\'' {
			j := i + 1
			for j < len(source) && source[j] != c {
				if source[j] == '\\' {
					j++
				}
				j++
			}
			if j >= len(source) {
				j = len(source) - 1
			}
			out = append(out, source[i:j+1]...)
			i = j + 1
			continue
		}
		if c == '}' && len(out) > 0 && out[len(out)-1] == ';' {
			out = out[:len(out)-1]
		}
		out = append(out, c)
		i++
	}
	return out
}

func indexFrom(s, sub string, from int) int {
	for i := from; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return i
		}
	}
	return -1
}

// dropsSpaceBefore are the characters no whitespace before changes the meaning of. Not ':' — a space
// before it is a descendant combinator.
func dropsSpaceBefore(c byte) bool {
	switch c {
	case '{', '}', ';', ',', '>', ')', '!':
		return true
	}
	return false
}

// dropsSpaceAfter are the characters no whitespace after changes the meaning of.
func dropsSpaceAfter(c byte) bool {
	switch c {
	case '{', '}', ';', ',', '>', '(', ':':
		return true
	}
	return false
}
