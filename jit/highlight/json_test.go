package highlight

import "testing"

// Each row pins one rule of tokenizeJSON (json.go): keys against values,
// constants, signed numbers, and the invalid JSON people paste.
func TestJSON(t *testing.T) {
	checkExact(t, "json", []tokenCase{
		{"\"say \\\"hi\\\" \\\\ \\/ \x5cu00e9\"", tokensOf(String, "\"say \\\"hi\\\" \\\\ \\/ \x5cu00e9\"")},
		{"{\"a\": 1}", tokensOf(
			Punctuation, "{",
			Property, "\"a\"",
			Punctuation, ":",
			Plain, " ",
			Number, "1",
			Punctuation, "}",
		)},
		{"\"just a string\"", tokensOf(
			String, "\"just a string\"",
		)},
		{"[true, false, null]", tokensOf(
			Punctuation, "[",
			Constant, "true",
			Punctuation, ",",
			Plain, " ",
			Constant, "false",
			Punctuation, ",",
			Plain, " ",
			Constant, "null",
			Punctuation, "]",
		)},
		{"[-0.75, 2.5E+1, 1e6, 0, -1]", tokensOf(
			Punctuation, "[",
			Number, "-0.75",
			Punctuation, ",",
			Plain, " ",
			Number, "2.5E+1",
			Punctuation, ",",
			Plain, " ",
			Number, "1e6",
			Punctuation, ",",
			Plain, " ",
			Number, "0",
			Punctuation, ",",
			Plain, " ",
			Number, "-1",
			Punctuation, "]",
		)},
		{"{\"a\"\n  : \"b\"}", tokensOf(
			Punctuation, "{",
			Property, "\"a\"",
			Plain, "\n  ",
			Punctuation, ":",
			Plain, " ",
			String, "\"b\"",
			Punctuation, "}",
		)},
		{"\"abc\n\"x\"", tokensOf(
			String, "\"abc",
			Plain, "\n",
			String, "\"x\"",
		)},
		{"// comment\n{} /* block */", tokensOf(
			Comment, "// comment",
			Plain, "\n",
			Punctuation, "{}",
			Plain, " ",
			Comment, "/* block */",
		)},
		{"{\"a\": 1 /* open", tokensOf(
			Punctuation, "{",
			Property, "\"a\"",
			Punctuation, ":",
			Plain, " ",
			Number, "1",
			Plain, " ",
			Comment, "/* open",
		)},
		{"{a: 'b'}", tokensOf(
			Punctuation, "{",
			Property, "a",
			Punctuation, ":",
			Plain, " ",
			String, "'b'",
			Punctuation, "}",
		)},
		{"[\"a\", \"b\"]", tokensOf(
			Punctuation, "[",
			String, "\"a\"",
			Punctuation, ",",
			Plain, " ",
			String, "\"b\"",
			Punctuation, "]",
		)},
		{"[yes, @, #]", tokensOf(
			Punctuation, "[",
			Plain, "yes",
			Punctuation, ",",
			Plain, " @",
			Punctuation, ",",
			Plain, " #",
			Punctuation, "]",
		)},
		{"[NaN, Infinity, -Infinity, +Infinity]", tokensOf(
			Punctuation, "[",
			Constant, "NaN",
			Punctuation, ",",
			Plain, " ",
			Constant, "Infinity",
			Punctuation, ",",
			Plain, " ",
			Constant, "-Infinity",
			Punctuation, ",",
			Plain, " ",
			Constant, "+Infinity",
			Punctuation, "]",
		)},
		{"{\n\"a\":1\n}", tokensOf(
			Punctuation, "{",
			Plain, "\n",
			Property, "\"a\"",
			Punctuation, ":",
			Number, "1",
			Plain, "\n",
			Punctuation, "}",
		)},
		{"{\"tên\": \"Cà phê\", \"日本\": \"😀\"}", tokensOf(
			Punctuation, "{",
			Property, "\"tên\"",
			Punctuation, ":",
			Plain, " ",
			String, "\"Cà phê\"",
			Punctuation, ",",
			Plain, " ",
			Property, "\"日本\"",
			Punctuation, ":",
			Plain, " ",
			String, "\"😀\"",
			Punctuation, "}",
		)},
		{"{\"a:b\": \"c:d\"}", tokensOf(
			Punctuation, "{",
			Property, "\"a:b\"",
			Punctuation, ":",
			Plain, " ",
			String, "\"c:d\"",
			Punctuation, "}",
		)},
		{"\"a\": \"b\": \"c\"", tokensOf(
			Property, "\"a\"",
			Punctuation, ":",
			Plain, " ",
			Property, "\"b\"",
			Punctuation, ":",
			Plain, " ",
			String, "\"c\"",
		)},
		{"{\"a\": [1, {\"b\": [2, 3]}]}", tokensOf(
			Punctuation, "{",
			Property, "\"a\"",
			Punctuation, ":",
			Plain, " ",
			Punctuation, "[",
			Number, "1",
			Punctuation, ",",
			Plain, " ",
			Punctuation, "{",
			Property, "\"b\"",
			Punctuation, ":",
			Plain, " ",
			Punctuation, "[",
			Number, "2",
			Punctuation, ",",
			Plain, " ",
			Number, "3",
			Punctuation, "]}]}",
		)},
		{"{\"x\": .5, \"y\": +10, \"z\": 1.}", tokensOf(
			Punctuation, "{",
			Property, "\"x\"",
			Punctuation, ":",
			Plain, " ",
			Number, ".5",
			Punctuation, ",",
			Plain, " ",
			Property, "\"y\"",
			Punctuation, ":",
			Plain, " ",
			Number, "+10",
			Punctuation, ",",
			Plain, " ",
			Property, "\"z\"",
			Punctuation, ":",
			Plain, " ",
			Number, "1",
			Plain, ".",
			Punctuation, "}",
		)},
	})
}

// The samples read right where it matters, in order: a strict document and
// a commented configuration.
func TestJSONSample(t *testing.T) {
	checkContains(t, "json", []tokenCase{
		{javascriptSample(t, "json", "package.json"), tokensOf(
			Property, `"name"`, String, `"@kitwork/quancaphe"`,
			Property, `"private"`, Constant, "true",
			Property, `"ratio"`, Number, "-0.75",
			Property, `"weekday"`, Number, "7",
			Number, "1e6", Number, "2.5E+1", Number, "-1.5e-3",
			Constant, "null",
			Property, `"menu"`, Property, `"id"`, String, `"ca-phe-sua-da"`, Number, "24.5",
			Property, `"Content-Security-Policy"`,
			String, `"営業中"`,
			Number, "6.02e23", Number, "1E-7", Number, "123456789012345678901234567890",
			Property, `"keywords"`, String, `"menu"`,
		)},
		{javascriptSample(t, "json", "tsconfig.json"), tokensOf(
			Comment, "// Cấu hình kiểu tsconfig: JSON có chú thích, như người ta vẫn dán.",
			Comment, "/* Biên dịch */",
			Property, `"strict"`, Constant, "true", Comment, "// bật mọi kiểm tra",
			Property, `'lib'`, String, `'DOM'`,
			Property, "maxNodeModuleJsDepth",
			Number, ".5", Number, "+10", Constant, "NaN", Constant, "-Infinity",
			String, `"dist"`,
		)},
	})
}
