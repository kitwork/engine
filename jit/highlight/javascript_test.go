// An operator is tried only when its first byte is in javascriptOperatorStarts:
// one missing there would read as plain text.
func TestJavaScriptOperatorStartsCoverEveryOperator(t *testing.T) {
	for _, operator := range javascriptOperators {
		if strings.IndexByte(javascriptOperatorStarts, operator[0]) < 0 {
			t.Errorf("operator %q starts with a byte missing from javascriptOperatorStarts %q", operator, javascriptOperatorStarts)
		}
		if tokens := tokenizeWith(tokenizeJavaScript, "a "+operator+" b"); len(tokens) != 3 || tokens[1] != (Token{Kind: Operator, Text: operator}) {
			t.Errorf("%q reads as %s, want the operator alone", "a "+operator+" b", describe(tokens))
		}
	}
}

// javascriptSample is testdata/<language>/<name>, for the javascript family's
// sample checks.
func javascriptSample(t *testing.T, language, name string) string {
	t.Helper()
	for _, item := range fixturesFor(t, language) {
		if filepath.Base(item.path) == name {
			return item.source
		}
	}
	t.Fatalf("testdata/%s/%s is missing", language, name)
	return ""
}

